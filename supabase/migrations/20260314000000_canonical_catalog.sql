create table if not exists catalog_sync_runs (
  id bigint generated by default as identity primary key,
  provider text not null check (provider in ('anilist', 'mangadex', 'kitsu', 'jikan', 'manual', 'all')),
  run_type text not null default 'ingest' check (run_type in ('ingest', 'enrichment', 'reconcile', 'audit')),
  status text not null default 'running' check (status in ('running', 'completed', 'failed')),
  records_processed integer not null default 0,
  error_message text,
  started_at timestamptz not null default now(),
  finished_at timestamptz
);

create table if not exists catalog_merge_queue (
  id bigint generated by default as identity primary key,
  source_title_id bigint not null references canonical_titles(id) on delete cascade,
  candidate_title_id bigint not null references canonical_titles(id) on delete cascade,
  confidence numeric(5,2),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  reason text,
  created_at timestamptz not null default now(),
  reviewed_at timestamptz
);

