create or replace view catalog_titles_view as
select
  ct.id,
  ct.slug,
  ct.canonical_title,
  ct.type,
  ct.subtype,
  ct.origin_country,
  ct.origin_language,
  ct.status,
  ct.release_year,
  ct.episodes,
  ct.chapters,
  ct.volumes,
  ct.duration_minutes,
  ct.is_adult,
  ct.cover_image,
  ct.banner_image,
  ct.synopsis,
  ct.avg_score,
  ct.popularity_score,
  ct.editorial_score,
  ct.last_synced_at,
  array_remove(array_agg(distinct tg.genre_name), null) as genres,
  array_remove(array_agg(distinct tt.tag_name), null) as tags
from canonical_titles ct
left join title_genres tg on tg.canonical_title_id = ct.id
left join title_tags tt on tt.canonical_title_id = ct.id
group by ct.id;

create or replace function set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists trg_canonical_titles_updated_at on canonical_titles;
create trigger trg_canonical_titles_updated_at
before update on canonical_titles
for each row
execute function set_updated_at();
