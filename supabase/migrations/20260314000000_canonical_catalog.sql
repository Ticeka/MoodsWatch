create extension if not exists pgcrypto;

create table if not exists canonical_titles (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  canonical_title text not null,
  type text not null check (type in ('anime', 'manga')),
  subtype text not null default 'anime' check (subtype in ('anime', 'manga', 'manhwa', 'manhua', 'webtoon')),
  origin_country text,
  origin_language text,
  status text default 'ongoing' check (status in ('ongoing', 'completed', 'upcoming', 'hiatus', 'cancelled')),
  release_year integer,
  episodes integer,
  chapters integer,
  volumes integer,
  duration_minutes integer,
  is_adult boolean not null default false,
  cover_image text,
  banner_image text,
  synopsis text,
  avg_score numeric(5,2),
  popularity_score numeric(12,2),
  editorial_score numeric(5,2),
  raw_payload jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_synced_at timestamptz
);

create table if not exists title_aliases (
  id bigint generated by default as identity primary key,
  canonical_title_id bigint not null references canonical_titles(id) on delete cascade,
  alias text not null,
  language_code text,
  alias_type text not null default 'alternate' check (alias_type in ('canonical', 'english', 'romaji', 'native', 'localized', 'synonym')),
  is_primary boolean not null default false,
  source_provider text,
  created_at timestamptz not null default now()
);

create table if not exists title_source_refs (
  id bigint generated by default as identity primary key,
  canonical_title_id bigint not null references canonical_titles(id) on delete cascade,
  provider text not null check (provider in ('anilist', 'mangadex', 'kitsu', 'jikan', 'manual')),
  external_id text not null,
  external_url text,
  source_priority integer not null default 100,
  raw_payload jsonb,
  fetched_at timestamptz not null default now(),
  last_synced_at timestamptz not null default now(),
  unique (provider, external_id)
);

create table if not exists title_genres (
  id bigint generated by default as identity primary key,
  canonical_title_id bigint not null references canonical_titles(id) on delete cascade,
  genre_name text not null,
  normalized_name text generated always as (lower(genre_name)) stored,
  unique (canonical_title_id, normalized_name)
);

create table if not exists title_tags (
  id bigint generated by default as identity primary key,
  canonical_title_id bigint not null references canonical_titles(id) on delete cascade,
  tag_name text not null,
  normalized_name text generated always as (lower(tag_name)) stored,
  weight numeric(5,2),
  source_provider text,
  unique (canonical_title_id, normalized_name)
);

create table if not exists title_relations (
  id bigint generated by default as identity primary key,
  source_title_id bigint not null references canonical_titles(id) on delete cascade,
  target_title_id bigint not null references canonical_titles(id) on delete cascade,
  relation_type text not null check (relation_type in ('sequel', 'prequel', 'adaptation', 'side_story', 'shared_universe', 'related')),
  source_provider text,
  unique (source_title_id, target_title_id, relation_type)
);

create table if not exists title_availability (
  id bigint generated by default as identity primary key,
  canonical_title_id bigint not null references canonical_titles(id) on delete cascade,
  platform_name text not null,
  region_code text,
  url text not null,
  is_official boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists moods (
  id text primary key,
  name_th text not null,
  name_en text not null,
  icon text,
  color text,
  description text
);

create table if not exists title_moods (
  canonical_title_id bigint not null references canonical_titles(id) on delete cascade,
  mood_id text not null references moods(id) on delete cascade,
  primary key (canonical_title_id, mood_id)
);

