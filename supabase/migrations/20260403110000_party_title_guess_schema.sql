-- ============================================================
-- Party Title Guess schema
-- 2026-04-03
--
-- Goal:
-- - keep catalog character data reusable
-- - add gameplay metadata to title_characters
-- - add curated set/question/clue tables for the Title Guess mode
-- - support 4 ordered clue cards without relying on protagonist clues
