-- ----------------------------------------------------------------
-- 8. Counter sync helpers
-- ----------------------------------------------------------------
create or replace function public.sync_party_title_guess_question_count()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    update public.party_title_guess_sets
    set question_count = question_count + 1
    where id = new.set_id;
  elsif tg_op = 'DELETE' then
    update public.party_title_guess_sets
    set question_count = greatest(0, question_count - 1)
    where id = old.set_id;
  elsif tg_op = 'UPDATE' and new.set_id <> old.set_id then
    update public.party_title_guess_sets
    set question_count = greatest(0, question_count - 1)
    where id = old.set_id;

    update public.party_title_guess_sets
    set question_count = question_count + 1
    where id = new.set_id;
  end if;

  return null;
end;
$$;

drop trigger if exists trg_party_title_guess_questions_count
  on public.party_title_guess_questions;
create trigger trg_party_title_guess_questions_count
  after insert or delete or update of set_id on public.party_title_guess_questions
  for each row execute function public.sync_party_title_guess_question_count();

create or replace function public.sync_party_title_guess_like_count()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    update public.party_title_guess_sets
    set like_count = like_count + 1
    where id = new.set_id;
  elsif tg_op = 'DELETE' then
    update public.party_title_guess_sets
    set like_count = greatest(0, like_count - 1)
    where id = old.set_id;
  end if;

  return null;
end;
$$;

drop trigger if exists trg_party_title_guess_set_likes_count
  on public.party_title_guess_set_likes;
create trigger trg_party_title_guess_set_likes_count
  after insert or delete on public.party_title_guess_set_likes
  for each row execute function public.sync_party_title_guess_like_count();

create or replace function public.increment_party_title_guess_play_count(p_set_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.party_title_guess_sets
  set play_count = play_count + 1
  where id = p_set_id
    and (
      visibility in ('public', 'unlisted')
      or owner_user_id = auth.uid()
      or public.is_staff_user()
    );
end;
$$;

-- ----------------------------------------------------------------
-- 9. RLS
-- ----------------------------------------------------------------
alter table public.party_title_guess_sets enable row level security;
alter table public.party_title_guess_questions enable row level security;
alter table public.party_title_guess_clues enable row level security;
alter table public.party_title_guess_set_likes enable row level security;

drop policy if exists "Read party_title_guess_sets" on public.party_title_guess_sets;
create policy "Read party_title_guess_sets"
  on public.party_title_guess_sets for select
  using (
    public.is_staff_user()
    or visibility in ('public', 'unlisted')
    or owner_user_id = auth.uid()
  );

drop policy if exists "Create party_title_guess_sets" on public.party_title_guess_sets;
create policy "Create party_title_guess_sets"
  on public.party_title_guess_sets for insert
  with check (
    auth.uid() is not null
    and owner_user_id = auth.uid()
    and is_official = false
  );

drop policy if exists "Update party_title_guess_sets" on public.party_title_guess_sets;
create policy "Update party_title_guess_sets"
  on public.party_title_guess_sets for update
  using (
    owner_user_id = auth.uid()
    or public.is_staff_user()
  )
  with check (
    (owner_user_id = auth.uid() and is_official = false)
    or public.is_staff_user()
  );

drop policy if exists "Delete party_title_guess_sets" on public.party_title_guess_sets;
create policy "Delete party_title_guess_sets"
  on public.party_title_guess_sets for delete
  using (
    owner_user_id = auth.uid()
    or public.is_staff_user()
  );

drop policy if exists "Read party_title_guess_questions" on public.party_title_guess_questions;
create policy "Read party_title_guess_questions"
  on public.party_title_guess_questions for select
  using (
    public.is_staff_user()
    or exists (
      select 1
      from public.party_title_guess_sets s
      where s.id = party_title_guess_questions.set_id
        and (
          s.visibility in ('public', 'unlisted')
          or s.owner_user_id = auth.uid()
        )
    )
  );

drop policy if exists "Write party_title_guess_questions" on public.party_title_guess_questions;
create policy "Write party_title_guess_questions"
  on public.party_title_guess_questions for all
  using (
    public.is_staff_user()
    or exists (
      select 1
      from public.party_title_guess_sets s
      where s.id = party_title_guess_questions.set_id
        and s.owner_user_id = auth.uid()
    )
  )
  with check (
    public.is_staff_user()
    or exists (
      select 1
      from public.party_title_guess_sets s
      where s.id = party_title_guess_questions.set_id
        and s.owner_user_id = auth.uid()
    )
  );

drop policy if exists "Read party_title_guess_clues" on public.party_title_guess_clues;
create policy "Read party_title_guess_clues"
  on public.party_title_guess_clues for select
  using (
    public.is_staff_user()
    or exists (
      select 1
      from public.party_title_guess_questions q
      join public.party_title_guess_sets s on s.id = q.set_id
      where q.id = party_title_guess_clues.question_id
        and (
          s.visibility in ('public', 'unlisted')
          or s.owner_user_id = auth.uid()
        )
    )
  );

drop policy if exists "Write party_title_guess_clues" on public.party_title_guess_clues;
create policy "Write party_title_guess_clues"
  on public.party_title_guess_clues for all
  using (
    public.is_staff_user()
    or exists (
      select 1
      from public.party_title_guess_questions q
      join public.party_title_guess_sets s on s.id = q.set_id
      where q.id = party_title_guess_clues.question_id
        and s.owner_user_id = auth.uid()
    )
  )
  with check (
    public.is_staff_user()
    or exists (
      select 1
      from public.party_title_guess_questions q
      join public.party_title_guess_sets s on s.id = q.set_id
      where q.id = party_title_guess_clues.question_id
        and s.owner_user_id = auth.uid()
    )
  );

drop policy if exists "Read party_title_guess_set_likes" on public.party_title_guess_set_likes;
create policy "Read party_title_guess_set_likes"
  on public.party_title_guess_set_likes for select
  using (true);

drop policy if exists "Like party_title_guess_sets" on public.party_title_guess_set_likes;
create policy "Like party_title_guess_sets"
  on public.party_title_guess_set_likes for insert
  with check (
    auth.uid() is not null
    and user_id = auth.uid()
    and exists (
      select 1
      from public.party_title_guess_sets s
      where s.id = party_title_guess_set_likes.set_id
        and s.visibility in ('public', 'unlisted')
    )
  );

drop policy if exists "Unlike party_title_guess_sets" on public.party_title_guess_set_likes;
create policy "Unlike party_title_guess_sets"
  on public.party_title_guess_set_likes for delete
  using (
    user_id = auth.uid()
    or public.is_staff_user()
  );

