-- ----------------------------------------------------------------
-- 1. title_characters gameplay metadata
-- ----------------------------------------------------------------
alter table public.title_characters
  add column if not exists is_primary_protagonist boolean not null default false,
  add column if not exists is_guess_disabled boolean not null default false,
  add column if not exists guess_priority smallint not null default 0,
  add column if not exists guess_note text;

alter table public.title_characters
  drop constraint if exists title_characters_guess_priority_check;

alter table public.title_characters
  add constraint title_characters_guess_priority_check
  check (guess_priority between -10 and 10);

create index if not exists idx_title_characters_guess_pool
  on public.title_characters (
    canonical_title_id,
    is_guess_disabled,
    is_primary_protagonist,
    role,
    sort_order asc,
    guess_priority desc,
    id asc
  );

create index if not exists idx_title_characters_guess_enabled
  on public.title_characters (canonical_title_id, sort_order asc, id asc)
  where is_guess_disabled = false;

-- ----------------------------------------------------------------
-- 2. Title Guess set headers
-- ----------------------------------------------------------------
create table if not exists public.party_title_guess_sets (
  id bigint generated by default as identity primary key,
  owner_user_id uuid references auth.users(id) on delete set null,
  creator_name text not null default '',
  name text not null,
  description text,
  cover_url text,
  visibility text not null default 'public'
    check (visibility in ('public', 'unlisted', 'private')),
  is_official boolean not null default false,
  question_count integer not null default 0 check (question_count >= 0),
  like_count integer not null default 0 check (like_count >= 0),
  play_count integer not null default 0 check (play_count >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- ----------------------------------------------------------------
-- 3. Title Guess questions
-- ----------------------------------------------------------------
create table if not exists public.party_title_guess_questions (
  id bigint generated by default as identity primary key,
  set_id bigint not null
    references public.party_title_guess_sets(id) on delete cascade,
  answer_title_id bigint not null
    references public.canonical_titles(id) on delete cascade,
  answer_aliases jsonb not null default '[]'::jsonb,
  difficulty_tier smallint not null default 2,
  status text not null default 'draft'
    check (status in ('draft', 'ready', 'archived')),
  sort_order integer not null default 0,
  source_strategy text not null default 'manual'
    check (source_strategy in ('manual', 'auto', 'hybrid')),
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (set_id, answer_title_id)
);

alter table public.party_title_guess_questions
  drop constraint if exists party_title_guess_questions_difficulty_tier_check;

alter table public.party_title_guess_questions
  add constraint party_title_guess_questions_difficulty_tier_check
  check (difficulty_tier between 1 and 5);

-- ----------------------------------------------------------------
-- 4. Ordered clue cards per question
-- ----------------------------------------------------------------
create table if not exists public.party_title_guess_clues (
  id bigint generated by default as identity primary key,
  question_id bigint not null
    references public.party_title_guess_questions(id) on delete cascade,
  character_id bigint not null
    references public.title_characters(id) on delete restrict,
  clue_order smallint not null
    check (clue_order between 1 and 4),
  clue_role_bucket text not null default 'supporting'
    check (clue_role_bucket in ('background', 'supporting', 'main-side', 'wildcard')),
  character_name_snapshot text not null default '',
  character_name_native_snapshot text,
  character_image_url_snapshot text,
  is_manual_override boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (question_id, clue_order),
  unique (question_id, character_id)
);

-- ----------------------------------------------------------------
-- 5. Optional likes for public/unlisted sets
-- ----------------------------------------------------------------
create table if not exists public.party_title_guess_set_likes (
  id bigint generated by default as identity primary key,
  set_id bigint not null
    references public.party_title_guess_sets(id) on delete cascade,
  user_id uuid not null
    references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (set_id, user_id)
);

